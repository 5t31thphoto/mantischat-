#!/usr/bin/env python3
"""Regenerate MantisChat/mc_logo.h and web/mantis.png from the mascot art.
   python3 tools/make_logo.py path/to/mascot.jpeg"""
import sys
from PIL import Image
src = sys.argv[1] if len(sys.argv) > 1 else "tools/mascot.jpeg"
im = Image.open(src).convert("RGB")
BG = (187, 229, 189)                       # the art's mint backdrop
# square crop around the mantis (bbox 380..822 x 88..670)
cx, cy, half = 601, 382, 310
crop = im.crop((cx-half, cy-half, cx+half, cy+half))

def flatten(img, alpha=False):
    img = img.convert("RGBA")
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if abs(r-BG[0]) + abs(g-BG[1]) + abs(b-BG[2]) < 38:
                px[x, y] = (0, 0, 0, 0) if alpha else (*BG, 255)
    return img

def rgb565(r, g, b): return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

out = ["// generated by tools/make_logo.py -- do not edit",
       "#pragma once", "#include <stdint.h>",
       "#define MC_MINT_565 0x%04X" % rgb565(*BG)]
# Big mascot: 256-colour palette + 8-bit indices (16.5 KB instead of 32 KB of raw RGB565).
# The mint backdrop keeps its exact colour so it meets the MC_MINT_565 panel without a seam.
big = flatten(crop.resize((128, 128), Image.LANCZOS)).convert("RGB")
q = big.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pal = q.getpalette()[:256 * 3]
pal += [0] * (256 * 3 - len(pal))
bg_idx = q.getpixel((0, 0))
pal[bg_idx * 3:bg_idx * 3 + 3] = list(BG)
idx = [q.getpixel((x, y)) for y in range(128) for x in range(128)]
out.append("static const int MASCOT_L_W = 128, MASCOT_L_H = 128;")
out.append("static const uint16_t MASCOT_L_PAL[256] = {")
p565 = [rgb565(*pal[i * 3:i * 3 + 3]) for i in range(256)]
for i in range(0, 256, 16):
    out.append("  " + ",".join("0x%04X" % v for v in p565[i:i+16]) + ",")
out.append("};")
out.append("static const uint8_t MASCOT_L_IDX[%d] = {" % len(idx))
for i in range(0, len(idx), 32):
    out.append("  " + ",".join(str(v) for v in idx[i:i+32]) + ",")
out.append("};")
# Small mascot stays raw RGB565 (1 KB); its MC_MINT_565 pixels are drawn transparent.
small = flatten(crop.resize((22, 22), Image.LANCZOS)).convert("RGB")
vals = [rgb565(*small.getpixel((x, y))) for y in range(22) for x in range(22)]
out.append("static const int MASCOT_S_W = 22, MASCOT_S_H = 22;")
out.append("static const uint16_t MASCOT_S[%d] = {" % len(vals))
for i in range(0, len(vals), 16):
    out.append("  " + ",".join("0x%04X" % v for v in vals[i:i+16]) + ",")
out.append("};")
open("MantisChat/mc_logo.h", "w").write("\n".join(out) + "\n")
flatten(crop.resize((256, 256), Image.LANCZOS), alpha=True).save("web/mantis.png")
flatten(crop.resize((64, 64), Image.LANCZOS), alpha=True).save("web/favicon.png")
print("ok")
