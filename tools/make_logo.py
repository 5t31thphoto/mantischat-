#!/usr/bin/env python3
"""Regenerate MantisChat/mc_logo.h and web/mantis.png from the mascot art.
   python3 tools/make_logo.py path/to/mascot.jpeg"""
import sys
from PIL import Image
src = sys.argv[1] if len(sys.argv) > 1 else "tools/mascot.jpeg"
im = Image.open(src).convert("RGB")
BG = (187, 229, 189)                       # the art's mint backdrop
# square crop around the mantis (bbox 380..822 x 88..670)
cx, cy, half = 601, 382, 310
crop = im.crop((cx-half, cy-half, cx+half, cy+half))

def flatten(img, alpha=False):
    img = img.convert("RGBA")
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if abs(r-BG[0]) + abs(g-BG[1]) + abs(b-BG[2]) < 38:
                px[x, y] = (0, 0, 0, 0) if alpha else (*BG, 255)
    return img

def rgb565(r, g, b): return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

out = ["// generated by tools/make_logo.py -- do not edit",
       "#pragma once", "#include <stdint.h>",
       "#define MC_MINT_565 0x%04X" % rgb565(*BG)]
for name, size in (("MASCOT_L", 128), ("MASCOT_S", 22)):
    small = flatten(crop.resize((size, size), Image.LANCZOS)).convert("RGB")
    vals = [rgb565(*small.getpixel((x, y))) for y in range(size) for x in range(size)]
    out.append("static const int %s_W = %d, %s_H = %d;" % (name, size, name, size))
    out.append("static const uint16_t %s[%d] = {" % (name, len(vals)))
    for i in range(0, len(vals), 16):
        out.append("  " + ",".join("0x%04X" % v for v in vals[i:i+16]) + ",")
    out.append("};")
open("MantisChat/mc_logo.h", "w").write("\n".join(out) + "\n")
flatten(crop.resize((256, 256), Image.LANCZOS), alpha=True).save("web/mantis.png")
flatten(crop.resize((64, 64), Image.LANCZOS), alpha=True).save("web/favicon.png")
print("ok")
